#!/usr/bin/env python3
"""Rebuild svg/0-9.svg, digits.js and src/digits.js from the files in svg/original/.

Drop your own ten digit SVGs into svg/original/ (named 0.svg ... 9.svg) and run:

    python3 tools/normalize.py

What it does to each file:
  * removes the opaque black backing <rect> and black-filled counters, so holes are real holes
  * measures the glyph's true bounds by rendering it (needs rsvg-convert and ImageMagick)
  * scales and centers it on a 56 x 80 tabular cell: cap line at y=8, baseline at y=72
  * renames gradient IDs to d<digit>g<n> so all ten can be inlined on one page

Requirements: Python 3.8+, rsvg-convert (librsvg) and ImageMagick 7 (`magick`).
  macOS:  brew install librsvg imagemagick
  Debian: sudo apt install librsvg2-bin imagemagick
"""
import json, os, re, subprocess, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'svg', 'original')
OUT = os.path.join(ROOT, 'svg')
VW, VH, CAP, TOP = 56, 80, 64, 8   # cell width, cell height, cap height, cap line
PX = 1600                          # render size used for measuring

def measure(svg_text, vb, tmp):
    src, png = os.path.join(tmp, 'm.svg'), os.path.join(tmp, 'm.png')
    open(src, 'w').write(svg_text)
    subprocess.run(['rsvg-convert', '-w', str(PX), '-h', str(PX), src, '-o', png], check=True)
    out = subprocess.run(['magick', png, '-alpha', 'extract', '-threshold', '2%', '-trim',
                          '-format', '%w %h %X %Y', 'info:'], capture_output=True, text=True, check=True).stdout
    w, h, x, y = (int(v) for v in out.split())
    k = vb / PX
    return w * k, h * k, x * k, y * k

def main():
    data = []
    with tempfile.TemporaryDirectory() as tmp:
        for d in range(10):
            orig = open(os.path.join(SRC, f'{d}.svg')).read()
            vb = float(re.search(r'viewBox="0 0 ([\d.]+)', orig).group(1))
            t = re.sub(r'<!--.*?-->\s*', '', orig, flags=re.S)
            t = re.sub(r'<rect [^>]*fill="#000"/>\s*', '', t)
            t = re.sub(r'<path [^>]*fill="#000"/>\s*', '', t)
            ids = list(dict.fromkeys(re.findall(r'id="([^"]+)"', t)))  # order of appearance, stable across runs
            for n, old in enumerate(ids):
                t = t.replace(f'"{old}"', f'"d{d}g{n}"').replace(f'#{old})', f'#d{d}g{n})')
            w, h, x, y = measure(t, vb, tmp)
            s = CAP / h
            tx, ty = VW / 2 - (x + w / 2) * s, TOP - y * s
            m = re.search(r'<defs>.*?</defs>', t, re.S)
            defs = m.group(0) if m else '<defs></defs>'
            paths = re.findall(r'<path [^>]*/>', t)
            # Highlight lines are stroke-only and relied on fill="none" from the root <svg>.
            # Make it explicit so the paths render correctly wherever they are inlined.
            paths = [p if ' fill=' in p else p.replace('<path ', '<path fill="none" ', 1) for p in paths]
            body = '\n    '.join(paths)
            open(os.path.join(OUT, f'{d}.svg'), 'w').write(
                f'<svg xmlns="http://www.w3.org/2000/svg" width="{VW}" height="{VH}" fill="none" viewBox="0 0 {VW} {VH}">\n'
                f'  {defs}\n  <g transform="translate({tx:.3f} {ty:.3f}) scale({s:.5f})">\n    {body}\n  </g>\n</svg>\n')
            data.append({'defs': defs, 'paths': paths, 'tx': round(tx, 3), 'ty': round(ty, 3), 's': round(s, 5),
                         'orig': re.sub(r'<!--.*?-->\s*', '', orig, flags=re.S),
                         'top': round(y / vb * 100, 1), 'bot': round((y + h) / vb * 100, 1)})
            print(f'{d}: top {y / vb * 100:5.1f}%  bottom {(y + h) / vb * 100:5.1f}%  height {h / vb * 100:5.1f}%  -> scale {s:.4f}')
    with open(os.path.join(ROOT, 'digits.js'), 'w') as f:
        f.write('// Generated by tools/normalize.py from svg/original/*.svg. Do not edit by hand.\n')
        f.write('// Each entry: defs + paths of one digit, the transform that places it on the 56x80 cell,\n'
                '// the original file (for the audit) and its measured top/bottom in % of its own artboard.\n')
        f.write('window.FACET_DIGITS = [\n' + ',\n'.join(json.dumps(x, separators=(',', ':')) for x in data) + '\n];\n')
    # ES module for the npm package: geometry only, no originals or audit numbers
    os.makedirs(os.path.join(ROOT, 'src'), exist_ok=True)
    with open(os.path.join(ROOT, 'src', 'digits.js'), 'w') as f:
        f.write('// Generated by tools/normalize.py from svg/original/*.svg. Do not edit by hand.\n')
        f.write('// Digit artwork: CC BY-NC 4.0, see LICENSE-ASSETS.md.\n')
        f.write('export const DIGITS = [\n' + ',\n'.join(
            json.dumps({k: x[k] for k in ('defs', 'paths', 'tx', 'ty', 's')}, separators=(',', ':')) for x in data) + '\n];\n')
    print('Wrote svg/0-9.svg, digits.js and src/digits.js')

if __name__ == '__main__':
    main()
